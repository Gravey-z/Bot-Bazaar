import { check, positiveU64, record } from "../wire.js";
import { createLivingTownCall } from "./calls.js";
import { createLivingTownCompletionCall } from "./completion.js";

const methods = {
  register_player: "register_player", create_shop: "create_shop", rename_shop: "rename_shop",
  buy_item: "buy_from_merchant", start_production: "start_production", complete_production: "complete_production",
  set_listing: "set_listing", cancel_listing: "cancel_listing", purchase_upgrade: "purchase_upgrade",
} as const;
export type GuestAction = keyof typeof methods;
export function guestActionRequest(value: unknown) {
  const r = record(value);
  check(Object.keys(r).sort().join() === "action,parameters,requestId,validUntilNs", "invalid guest request fields");
  check(typeof r["requestId"] === "string" && /^[a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12}$/.test(r["requestId"]), "guest request ID required");
  check(typeof r["action"] === "string" && Object.hasOwn(methods, r["action"]), "unsupported guest action");
  const action = r["action"] as GuestAction, method = methods[action], parameters = record(r["parameters"]);
  check(!Object.hasOwn(parameters, "command"), "guest commands are generated by the server");
  const validUntilNs = positiveU64(r["validUntilNs"]);
  // Reuse the SDK's exact argument decoders, but never accept a transaction,
  // signer, receiver, access key or client-selected command sequence.
  if (method === "complete_production") createLivingTownCompletionCall(parameters);
  else createLivingTownCall(method, { ...parameters, command: { sequence: "1", config_version: "1", valid_until_ns: validUntilNs } });
  return { requestId: r["requestId"], action, parameters, validUntilNs };
}
export type GuestActionRequest = ReturnType<typeof guestActionRequest>;
export function guestActionMethod(action: GuestAction) { return methods[action]; }
